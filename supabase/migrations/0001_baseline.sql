-- Modulos de datos con el patron estandar
do $$
declare t text;
begin
  foreach t in array array[
    'personas','actividades','participaciones','capacidad_mensual',
    'portafolio','tareas','radar_paises','contactos_paises','calendario_visitas'
  ] loop
    execute format('create policy sel_%1$s on public.%1$I for select to authenticated using (true)', t);
    execute format('create policy ins_%1$s on public.%1$I for insert to authenticated with check (public.puede_editar())', t);
    execute format('create policy upd_%1$s on public.%1$I for update to authenticated using (public.puede_editar()) with check (public.puede_editar())', t);
    execute format('create policy del_%1$s on public.%1$I for delete to authenticated using (public.puede_editar())', t);
  end loop;
end $$;

