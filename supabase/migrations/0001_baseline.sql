-- Genera codigos correlativos por modulo: OPT-001, TAR-001, RAD-001, VJ-001, CI-001
create or replace function public.set_codigo(pref text, tabla text)
returns text language plpgsql set search_path = 'public' as $$
declare n int;
begin
  execute format(
    'select coalesce(max(nullif(regexp_replace(codigo, ''\D'', '''', ''g''), '''')::int), 0) + 1 from %I where codigo like %L',
    tabla, pref || '-%'
  ) into n;
  return pref || '-' || lpad(n::text, 3, '0');
end $$;

create or replace function public.tocar_updated_at()
returns trigger language plpgsql set search_path = 'public' as $$
begin new.updated_at := now(); return new; end $$;

