-- Registra quien cambio que, cuando y con que valor anterior.
create or replace function public.registrar_historial()
returns trigger language plpgsql security definer set search_path = 'public' as $$
declare
  quien text;
  uid uuid := auth.uid();
  k text; va text; vd text; ident text;
begin
  select coalesce(nombre, email) into quien from usuarios where id = uid;
  quien := coalesce(quien, 'sistema');
  ident := coalesce((to_jsonb(coalesce(new, old)) ->> 'id'), '');

  if tg_op = 'INSERT' then
    insert into historial (tabla, fila_id, accion, usuario_id, usuario)
    values (tg_table_name, ident, 'creó', uid, quien);
    return new;
  elsif tg_op = 'DELETE' then
    insert into historial (tabla, fila_id, accion, usuario_id, usuario, antes)
    values (tg_table_name, ident, 'eliminó', uid, quien, left(to_jsonb(old)::text, 500));
    return old;
  else
    for k in select jsonb_object_keys(to_jsonb(new)) loop
      if k in ('updated_at','created_at') then continue; end if;
      va := to_jsonb(old) ->> k;
      vd := to_jsonb(new) ->> k;
      if coalesce(va,'') <> coalesce(vd,'') then
        insert into historial (tabla, fila_id, campo, antes, despues, accion, usuario_id, usuario)
        values (tg_table_name, ident, k, va, vd, 'editó', uid, quien);
      end if;
    end loop;
    return new;
  end if;
end $$;

-- Crea el perfil en public.usuarios cuando se da de alta en auth.users
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = 'public' as $$
begin
  insert into usuarios (id, email, nombre)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email,'@',1)))
  on conflict (id) do nothing;
  return new;
end $$;

-- Impide que alguien se auto-promueva de rol o se reactive solo
create or replace function public.proteger_rol()
returns trigger language plpgsql security definer set search_path = 'public' as $$
begin
  if (new.rol is distinct from old.rol or new.activo is distinct from old.activo) and not es_admin() then
    raise exception 'Solo un administrador puede cambiar el rol o el acceso de un usuario';
  end if;
  return new;
end $$;

