-- ---------------------------------------------------------------------
-- 6. Row Level Security
--
-- Patron general en los modulos de datos:
--   select                -> cualquier usuario autenticado (incluye lector)
--   insert/update/delete  -> puede_editar() (admin o editor)
--
-- Excepciones:
--   config_listas, ajustes -> solo es_admin() escribe
--   historial              -> solo lectura; lo escriben los triggers
--   usuarios               -> cada uno su perfil; roles y bajas solo admin
--   mejora_continua        -> solo admin borra (preserva trazabilidad)
--   secretos               -> RLS activo SIN politicas: inaccesible desde
--                             el cliente. Es intencional; el linter lo
--                             reporta como INFO y se acepta a proposito.
-- ---------------------------------------------------------------------

alter table public.personas            enable row level security;
