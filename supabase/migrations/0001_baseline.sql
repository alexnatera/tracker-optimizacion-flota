create or replace function public.set_codigo_portafolio()
returns trigger language plpgsql set search_path = 'public' as $$
declare n int;
begin
  if new.codigo is null or new.codigo = '' then
    select coalesce(max((regexp_replace(codigo,'\D','','g'))::int),0)+1 into n
      from portafolio where codigo like 'OPT-%';
    new.codigo := 'OPT-' || lpad(n::text,3,'0');
  end if;
  return new;
end $$;

