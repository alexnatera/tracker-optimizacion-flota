create or replace function public.es_admin()
returns boolean language sql security definer set search_path = 'public' as $$
  select exists (select 1 from usuarios where id = auth.uid() and rol = 'admin' and activo);
$$;

create or replace function public.puede_editar()
returns boolean language sql security definer set search_path = 'public' as $$
  select exists (select 1 from usuarios where id = auth.uid() and rol in ('admin','editor') and activo);
$$;

